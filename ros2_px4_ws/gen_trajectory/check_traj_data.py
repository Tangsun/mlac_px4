import numpy as np
import matplotlib.pyplot as plt
import os
import math

def main():
    # Construct the path to the trajectory file
    # Assuming the script is run from ros2_px4_ws
    script_dir = os.path.dirname(os.path.realpath(__file__))
    # Path relative to where generate_ref_traj.py saves files
    # generate_ref_traj.py saves to ../src/mlac_sim/traj_data relative to scripts dir
    # So, from ros2_px4_ws, it's src/mlac_sim/traj_data
    traj_file_path = os.path.join(
        os.path.dirname(script_dir), # up to ros2_px4_ws
        "src", "mlac_sim", "traj_data", 
        # "circle_r2.0_t15.0s_alt2.0_psi0deg_50hz_11col.npy"   # --> a simple circle, without yaw changes
        # "figure8_L4.0_W2.0_t10s_alt2.0_initpsi0deg_FORCEZEROPsi_50hz_11col.npy" # --> figure 8 with zero yaw
        "setpoint_hold_x0.0_y0.0_z2.0_t20.0s_psi60deg_50hz_11col.npy"   # --> ??? setpoint hold with yaw=60deg
        # "setpoint_rot_yaw_x0.0_y0.0_z2.0_t20.0s_initpsi0deg_rate15dps_50hz_8col.npy"    # --> setpoint hold with rotating yaw???
        # "N100_T30.0_spline_11col_zero_yaw.npy"
    )

    traj_idx = 22

    if not os.path.exists(traj_file_path):
        print(f"Error: Trajectory file not found at: {traj_file_path}")
        # Fallback for where mlac_mission_node might look for it (if installed)
        # This part is harder to guess without knowing your exact install structure
        # For now, we'll rely on the typical relative path from where generate_ref_traj.py saves it.
        # If you run mlac_mission_node, it uses get_package_share_directory.
        # For a simple script, direct relative path is easier if you run from workspace root.
        # Let's try a path assuming the script is in ros2_px4_ws/scripts
        # and the file is in ros2_px4_ws/src/mlac_sim/traj_data/
        # If this script is in ros2_px4_ws/scripts, then ../src/mlac_sim/traj_data/ is correct
        # for files generated by generate_ref_traj.py

        # Adjust this path if your file is located elsewhere relative to where you run this script
        # For example, if you run this script from ros2_px4_ws/src/mlac_sim/mlac_sim/
        # traj_file_path = os.path.join("traj_data", "circle_r2.0_t20.0_alt2.0_initpsi0dg_50hz_11col.npy")

        alt_path_from_ws_root = os.path.join("src", "mlac_sim", "mlac_sim", "traj_data", "circle_r2.0_t20.0_alt2.0_initpsi0dg_50hz_11col.npy")
        if os.path.exists(alt_path_from_ws_root):
            traj_file_path = alt_path_from_ws_root
        else:
            print(f"Alternative path also not found: {alt_path_from_ws_root}")
            print("Please ensure the trajectory file path is correct and the script is run from a suitable directory (e.g., ros2_px4_ws).")
            return

    print(f"Loading trajectory from: {traj_file_path}")
    try:
        trajectory_data = np.load(traj_file_path)
    except Exception as e:
        print(f"Error loading .npy file: {e}")
        return

    print(f"Trajectory shape: {trajectory_data.shape}")

    if trajectory_data.ndim != 2:
        print("Trajectory data is not a 2D array.")
        trajectory_data = trajectory_data[traj_idx]
        # return
    
    num_points = trajectory_data.shape[0]
    num_cols = trajectory_data.shape[1]

    if num_cols < 8:
        print(f"Error: Trajectory has only {num_cols} columns. Expected at least 8 for t, p, v, psi.")
        return
    
    time_col = trajectory_data[:, 0]
    psi_col_rad = trajectory_data[:, 7] # Column 7 is psi
    psi_col_deg = np.rad2deg(psi_col_rad)

    print("\n--- Sample Yaw Data ---")
    print(f"Total points: {num_points}")
    print(f"Time duration: {time_col[-1] - time_col[0]:.2f} seconds")
    
    sample_indices = [0, 1, 2, num_points // 4, num_points // 2, 3 * num_points // 4, num_points - 3, num_points - 2, num_points - 1]
    sample_indices = sorted(list(set(idx for idx in sample_indices if 0 <= idx < num_points))) # Ensure valid and unique

    print("Index | Time (s) | Psi (rad) | Psi (deg)")
    print("-----------------------------------------")
    for i in sample_indices:
        print(f"{i:<5} | {time_col[i]:<8.3f} | {psi_col_rad[i]:<9.3f} | {psi_col_deg[i]:<9.1f}")
    print("-----------------------------------------")

    # Plotting
    plt.figure(figsize=(12, 6))
    
    plt.subplot(1, 2, 1)
    plt.plot(time_col, psi_col_rad)
    plt.title('Desired Yaw (psi) vs. Time (Radians)')
    plt.xlabel('Time (s)')
    plt.ylabel('Yaw (radians)')
    plt.grid(True)

    plt.subplot(1, 2, 2)
    plt.plot(time_col, psi_col_deg)
    plt.title('Desired Yaw (psi) vs. Time (Degrees)')
    plt.xlabel('Time (s)')
    plt.ylabel('Yaw (degrees)')
    plt.grid(True)

    plt.tight_layout()
    
    # Also plot the XY path to see the circle and initial direction
    fig_xy, ax_xy = plt.subplots(figsize=(8,8))
    px_col = trajectory_data[:, 1]
    py_col = trajectory_data[:, 2]
    ax_xy.plot(px_col, py_col, label='XY Path')
    ax_xy.scatter(px_col[0], py_col[0], color='red', s=100, label='Start Point', zorder=5)
    
    # Plot initial heading vector
    arrow_len = 0.5
    initial_vx = trajectory_data[0, 4]
    initial_vy = trajectory_data[0, 5]
    # Or use psi:
    # initial_vx_from_psi = arrow_len * math.cos(psi_col_rad[0])
    # initial_vy_from_psi = arrow_len * math.sin(psi_col_rad[0])

    dt = 0.02

    ax_xy.arrow(px_col[0], py_col[0], initial_vx * dt, initial_vy*dt , # Scale arrow by dt for visibility or use fixed length
                head_width=0.1, head_length=0.15, fc='red', ec='red', label='Initial Velocity Vector')

    ax_xy.set_xlabel("X position (m)")
    ax_xy.set_ylabel("Y position (m)")
    ax_xy.set_title(f"XY Path (Initial Yaw: {psi_col_deg[0]:.1f} deg)")
    ax_xy.axis('equal')
    ax_xy.legend()
    ax_xy.grid(True)

    plt.show()

if __name__ == '__main__':
    main()